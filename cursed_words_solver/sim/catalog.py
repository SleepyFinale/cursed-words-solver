"""Run-level game catalog (items, characters, bosses) from data/game/run_catalog.json.

Generated by ``scripts/extract_run_catalog.py`` via reflection over Assembly-CSharp.
Slot classification follows ``ItemPools.AddItemsToPools``: 0 upgradeable components
→ stamp, 1 → sticker, 2 → pin (character item).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache

from cursed_words_solver.fingerprints import slugify
from cursed_words_solver.paths import data_path

_CATALOG_PATH = data_path("data", "game", "run_catalog.json")
_BOSS_TAXONOMY_PATH = data_path("data", "game", "boss_taxonomy.json")

# ItemPools excludes these rarities from the shop pools.
NON_SHOP_RARITIES = frozenset({"Unique", "Weird"})


@dataclass(frozen=True)
class ItemDef:
    game_class: str
    name: str
    slug: str
    rarity: str
    cost: int
    slot: str  # stamp | sticker | pin | other
    component_values: tuple[int, ...]
    component_increments: tuple[int, ...]
    tags: tuple[str, ...]
    dependency_tags: tuple[str, ...]
    function_tags: tuple[str, ...]
    is_food: bool
    is_animal: bool
    selling_prevented: bool

    @property
    def in_shop_pool(self) -> bool:
        return self.rarity not in NON_SHOP_RARITIES and self.slot in {"stamp", "sticker"}


@dataclass(frozen=True)
class CharacterDef:
    game_class: str
    name: str
    slug: str
    pin_class: str
    intro_items: tuple[str, ...]
    is_secret: bool


@dataclass(frozen=True)
class BossDef:
    game_class: str
    name: str
    boss_id: str  # repo boss id (boss_taxonomy.json), e.g. "mole"
    banned_floor_indexes: tuple[int, ...]
    difficulty_modifier: tuple[int, ...]
    difficulty_increase: tuple[int, ...]
    is_secret_character: bool
    can_be_summoned_by_michael: bool

    def floor_modification(self, floor_index: int, *, cursed: bool, harder_bosses: bool) -> int:
        """``BossModifier.SetFloorAdjustedModification`` (+ ``MakeCursed`` increment)."""
        idx = floor_index + 1 if harder_bosses else floor_index
        idx = min(idx, len(self.difficulty_modifier) - 1)
        value = self.difficulty_modifier[idx]
        if cursed:
            value += self.difficulty_increase[idx]
        return value


@dataclass(frozen=True)
class RunCatalog:
    items: dict[str, ItemDef]
    characters: dict[str, CharacterDef]
    bosses: dict[str, BossDef]
    items_by_slug: dict[str, ItemDef]

    def shop_pool(self, slot: str) -> list[ItemDef]:
        return [i for i in self.items.values() if i.slot == slot and i.in_shop_pool]

    def item_by_slug(self, slug: str) -> ItemDef | None:
        return self.items_by_slug.get(slug)

    def character(self, key: str) -> CharacterDef:
        """Look up by game class (``WetDennis``), display name, or slug."""
        if key in self.characters:
            return self.characters[key]
        low = slugify(key)
        for c in self.characters.values():
            if c.slug == low or slugify(c.game_class) == low:
                return c
        raise KeyError(key)


def _tuple(value: object) -> tuple:
    if not value:
        return ()
    return tuple(value) if isinstance(value, list) else (value,)


@lru_cache(maxsize=1)
def _boss_ids_by_class() -> dict[str, str]:
    if not _BOSS_TAXONOMY_PATH.is_file():
        return {}
    data = json.loads(_BOSS_TAXONOMY_PATH.read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for section in ("bosses", "hidden"):
        for boss_id, row in (data.get(section) or {}).items():
            if isinstance(row, dict) and row.get("game_class"):
                out[row["game_class"]] = boss_id
    return out


@lru_cache(maxsize=1)
def load_run_catalog() -> RunCatalog:
    data = json.loads(_CATALOG_PATH.read_text(encoding="utf-8"))
    items: dict[str, ItemDef] = {}
    for row in data.get("items") or []:
        if not row.get("ok"):
            continue
        comps = row.get("components") or []
        items[row["type"]] = ItemDef(
            game_class=row["type"],
            name=row.get("name") or row["type"],
            slug=slugify(row.get("name") or row["type"]),
            rarity=row.get("rarity") or "Common",
            cost=int(row.get("cost") or 0),
            slot=row.get("slot") or "other",
            component_values=tuple(int(c.get("value", 0)) for c in comps),
            component_increments=tuple(int(c.get("increment", 0)) for c in comps),
            tags=_tuple(row.get("tags")),
            dependency_tags=_tuple(row.get("dependency_tags")),
            function_tags=_tuple(row.get("function_tags")),
            is_food=bool(row.get("is_food")),
            is_animal=bool(row.get("is_animal")),
            selling_prevented=bool(row.get("selling_prevented")),
        )

    characters: dict[str, CharacterDef] = {}
    for row in data.get("characters") or []:
        if not row.get("ok"):
            continue
        characters[row["type"]] = CharacterDef(
            game_class=row["type"],
            name=row.get("name") or row["type"],
            slug=slugify(row.get("name") or row["type"]),
            pin_class=row.get("pin") or "",
            intro_items=_tuple(row.get("intro_items")),
            is_secret=bool(row.get("is_secret")),
        )

    boss_ids = _boss_ids_by_class()
    bosses: dict[str, BossDef] = {}
    for row in data.get("bosses") or []:
        if not row.get("ok"):
            continue
        bosses[row["type"]] = BossDef(
            game_class=row["type"],
            name=row.get("name") or row["type"],
            boss_id=boss_ids.get(row["type"], slugify(row["type"])),
            banned_floor_indexes=_tuple(row.get("banned_floor_indexes")),
            difficulty_modifier=_tuple(row.get("difficulty_modifier")),
            difficulty_increase=_tuple(row.get("difficulty_increase")),
            is_secret_character=bool(row.get("is_secret_character")),
            can_be_summoned_by_michael=bool(row.get("can_be_summoned_by_michael")),
        )
    return RunCatalog(
        items=items,
        characters=characters,
        bosses=bosses,
        items_by_slug={i.slug: i for i in items.values()},
    )
